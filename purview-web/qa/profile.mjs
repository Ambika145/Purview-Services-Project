import { chromium } from "@playwright/test";
const [base = "http://localhost:3200", w = "390", h = "844"] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: +w, height: +h } });
const cdp = await p.context().newCDPSession(p);
await cdp.send("Emulation.setCPUThrottlingRate", { rate: 4 });
await cdp.send("Profiler.enable");
await cdp.send("Profiler.setSamplingInterval", { interval: 200 });
await cdp.send("Profiler.start");
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.waitForTimeout(5000);
const { profile } = await cdp.send("Profiler.stop");
const dt = profile.timeDeltas; const self = new Map();
const byId = new Map(profile.nodes.map((n) => [n.id, n]));
profile.samples.forEach((id, i) => { const n = byId.get(id); const f = n.callFrame; const key = `${f.functionName || "(anon)"} @ ${(f.url || "").split("/").pop()}:${f.lineNumber}`; self.set(key, (self.get(key) || 0) + (dt[i] || 0) / 1000); });
const top = [...self.entries()].filter(([k]) => !/\(idle\)|\(program\)/.test(k)).sort((a, b) => b[1] - a[1]).slice(0, 18);
top.forEach(([k, v]) => console.log(Math.round(v).toString().padStart(6), "ms ", k));
console.log("DOM nodes:", await p.evaluate(() => document.querySelectorAll("*").length));
await b.close();
